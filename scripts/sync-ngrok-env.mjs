#!/usr/bin/env node
/**
 * Reads ngrok local API and writes web/.env.local with public URLs.
 * Also prints the public TCP address for GPS device testing.
 *
 * Usage: node scripts/sync-ngrok-env.mjs
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(root, 'web', '.env.local');

const NGROK_API = process.env.NGROK_API ?? 'http://127.0.0.1:4040/api/tunnels';

function portFromAddr(addr) {
  if (!addr) return null;
  const s = String(addr);
  const match = s.match(/:(\d+)$/);
  return match ? Number(match[1]) : null;
}

function pickWebUrl(tunnels) {
  const hit = tunnels.find((t) => portFromAddr(t.config?.addr) === 3000);
  if (!hit) return null;
  return hit.public_url?.startsWith('https://')
    ? hit.public_url
    : tunnels.map((t) => t.public_url).find((u) => u?.startsWith('https://')) ?? hit.public_url;
}

function pickTcpAddress(tunnels) {
  const hit = tunnels.find(
    (t) => t.proto === 'tcp' && portFromAddr(t.config?.addr) === 5023,
  );
  if (!hit?.public_url) return null;
  return hit.public_url.replace(/^tcp:\/\//, '');
}

async function main() {
  let data;
  try {
    const res = await fetch(NGROK_API);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    data = await res.json();
  } catch {
    console.error('Could not reach ngrok API at', NGROK_API);
    console.error('Start ngrok first:  ./scripts/start-ngrok.sh');
    process.exit(1);
  }

  const tunnels = data.tunnels ?? [];
  const webUrl = pickWebUrl(tunnels);
  const tcpAddress = pickTcpAddress(tunnels);

  if (!webUrl) {
    console.error('Expected tunnel on port 3000 (web). Found:');
    for (const t of tunnels) {
      console.error(' -', t.name, t.public_url, t.config?.addr);
    }
    process.exit(1);
  }

  const hostname = new URL(webUrl).hostname;

  const content = `# Auto-generated by scripts/sync-ngrok-env.mjs — do not commit
# Restart "pnpm dev" in web/ after this file changes.

ALLOWED_DEV_ORIGINS=${hostname}
NEXT_PUBLIC_APP_URL=${webUrl}
NEXT_PUBLIC_API_URL=${webUrl}/backend-api
NEXT_PUBLIC_WS_URL=${webUrl}
`;

  writeFileSync(envPath, content, 'utf8');

  console.log('Wrote web/.env.local\n');
  console.log('  Open on phone:', webUrl);
  console.log('  API (proxied):', `${webUrl}/backend-api`);
  console.log('  WebSocket:', webUrl);
  if (tcpAddress) {
    console.log('  GPS TCP:', tcpAddress);
    console.log('  Test GPS:');
    console.log(
      `    node scripts/send-gps-tcp.mjs --host ${tcpAddress.split(':')[0]} --port ${tcpAddress.split(':')[1] ?? '5023'} --imei 867530012345678 --lat 23.81 --lng 90.41`,
    );
  } else {
    console.log('  GPS TCP: not found (ensure gps-tcp tunnel is running on :5023)');
  }
  console.log('\nNext steps:');
  console.log('  1. cd web && pnpm dev   (restart if already running)');
  console.log('  2. Open on Poco F1:', `${webUrl}/bn/login`);
  console.log('  3. Driver login → Start Trip → Enable GPS');
  console.log('  4. Or send device GPS via TCP — see docs/TCP-GPS.md');
}

main();
